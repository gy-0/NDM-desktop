import assert from 'node:assert/strict'

// Runs inside qa-component-motion's private Electron profile and engine fixture.
export async function runFeedbackMotionCases({ app, win, startSampler, capture, checks }) {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1280, 820))
  await win.emulateMedia({ reducedMotion: 'no-preference' })
  const task = win.locator('[data-task-select="101"]')
  const menu = win.locator('[data-task-context-menu]')
  const entering = await startSampler('[data-task-context-menu]', 360, { waitForChange: true })
  await task.click({ button: 'right' })
  await menu.waitFor()
  const menuFrames = await entering.finish()
  assert.ok(menuFrames.some(frame => frame.opacity > 0 && frame.opacity < 1), 'Context menu must animate from its pointer anchor')
  await menu.getByRole('menuitem', { name: '复制下载链接', exact: false }).focus()
  await capture('06-context-menu')
  const leaving = await startSampler('[data-task-context-menu]')
  await win.keyboard.press('Escape')
  const exitFrames = await leaving.finish()
  await menu.waitFor({ state: 'hidden' })
  assert.ok(exitFrames.some(frame => frame.opacity > 0 && frame.opacity < 1), 'Context menu must retain its exit transition')
  assert.equal(await task.evaluate(node => node === document.activeElement), true, 'Context menu Escape must restore its task')
  checks.push({ name: 'Context menu entry/exit and task focus', passed: true, menuFrames, exitFrames })
  const closeInspector = win.getByRole('button', { name: '关闭任务详情', exact: true })
  if (await closeInspector.isVisible()) await closeInspector.click()
  await win.getByRole('searchbox', { name: '搜索下载任务' }).focus()
  await win.keyboard.press('Escape')
  await win.keyboard.press('Escape')

  const drag = async (type, hot = false, files = false) => win.evaluate(({ type, hot, files }) => {
    const transfer = new DataTransfer()
    if (files) transfer.items.add(new File(['fixture'], 'motion.txt', { type: 'text/plain' }))
    else transfer.setData('text/uri-list', 'https://example.invalid/motion-review.zip')
    const card = document.querySelector('[data-drop-card]')?.getBoundingClientRect()
    document.querySelector('.ndm-workspace').dispatchEvent(new DragEvent(type, {
      bubbles: true, cancelable: true, dataTransfer: transfer,
      clientX: hot && card ? card.x + card.width / 2 : 1,
      clientY: hot && card ? card.y + card.height / 2 : 1
    }))
  }, { type, hot, files })
  await drag('dragenter')
  await win.locator('[data-drop-card]').waitFor()
  const cold = await win.locator('[data-drop-card]').boundingBox()
  await drag('dragover', true)
  await win.locator('[data-drop-hot]').waitFor()
  await win.waitForTimeout(180)
  const hot = await win.locator('[data-drop-card]').boundingBox()
  assert.ok(Math.abs(cold.width - hot.width) < 1 && Math.abs(cold.height - hot.height) < 1, 'Drag feedback must not scale text or move the hit area')
  const moving = await win.locator('.download-drop-outline rect').evaluate(node => getComputedStyle(node).animationName)
  assert.notEqual(moving, 'none')
  await capture('07-link-drop-receiver')
  await win.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await win.locator('.download-drop-outline rect').evaluate(node => getComputedStyle(node).animationName), 'none')
  await drag('dragend')
  await win.locator('[data-download-drop-target]').waitFor({ state: 'hidden' })
  await drag('dragenter', false, true)
  assert.equal(await win.locator('[data-download-drop-target]').count(), 0, 'Local file drags must not become link offers')
  await win.emulateMedia({ reducedMotion: 'no-preference' })
  await drag('dragenter')
  await win.locator('[data-drop-card]').waitFor()
  await drag('drop', true)
  const composer = win.getByRole('dialog', { name: '添加下载', exact: true })
  await composer.waitFor()
  assert.equal(await composer.getByRole('textbox', { name: '下载链接', exact: true }).inputValue(), 'https://example.invalid/motion-review.zip')
  await win.keyboard.press('Escape')
  await composer.waitFor({ state: 'hidden' })
  checks.push({ name: 'Link receiver is stable, reduced-motion aware, excludes local files and opens review only', passed: true, cold, hot })

  await app.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('system:clipboard-snapshot')
    ipcMain.handle('system:clipboard-snapshot', () => ({ text: 'https://example.invalid/clipboard-motion.zip', changeCount: 811, selfWritten: false }))
  })
  await win.evaluate(() => window.dispatchEvent(new FocusEvent('focus')))
  const toast = win.locator('.clipboard-toast')
  await toast.waitFor()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(580, 680))
  const toastGeometry = await toast.evaluate(node => ({ rect: node.getBoundingClientRect().toJSON(), width: innerWidth }))
  assert.ok(toastGeometry.rect.x >= 0 && toastGeometry.rect.right <= toastGeometry.width)
  const dismiss = toast.getByRole('button', { name: '关闭剪贴板提示', exact: true })
  await dismiss.focus()
  const closing = await startSampler('.clipboard-toast', 420)
  await dismiss.click()
  const clipboardFrames = await closing.finish()
  await toast.waitFor({ state: 'hidden' })
  assert.ok(clipboardFrames.some(frame => frame.opacity > 0 && frame.opacity < 1), 'Production CSS seconds must retain the clipboard exit duration')
  assert.equal(await win.getByRole('searchbox', { name: '搜索下载任务' }).evaluate(node => node === document.activeElement), true)
  checks.push({ name: 'Clipboard offer narrow layout, exit frames and focus restoration', passed: true, toastGeometry, clipboardFrames })

  await app.evaluate(({ BrowserWindow, ipcMain }) => {
    BrowserWindow.getAllWindows()[0].setSize(1280, 820)
    ipcMain.removeHandler('system:install-disk-image')
    ipcMain.handle('system:install-disk-image', () => new Promise(resolve => setTimeout(() => resolve('合成测试：暂时无法安装，请重试。'), 220)))
  })
  const phase = async (phase, detail) => app.evaluate(({ BrowserWindow }, message) => {
    BrowserWindow.getAllWindows()[0].webContents.send('engine:event', message)
  }, { op: 'installProgress', path: '/tmp/NDM-motion-fixture.dmg', phase, detail })
  await phase('mounting')
  const activity = win.getByTestId('install-progress')
  await activity.waitFor()
  await win.waitForTimeout(220)
  const identity = await activity.getAttribute('data-activity-path')
  const statusSampler = await startSampler('[data-activity-status] [data-activity-text-current]', 360, { waitForChange: true })
  await phase('scanning')
  await activity.locator('[data-activity-status] [data-activity-text-current]').filter({ hasText: '正在查找应用' }).waitFor()
  const statusFrames = await statusSampler.finish()
  assert.ok(statusFrames.some(frame => frame.opacity > 0 && frame.opacity < 1), 'Installation stage text must show intermediate frames')
  await phase('failed', '合成安装失败')
  const retry = activity.getByRole('button', { name: '重试安装', exact: true })
  await retry.waitFor()
  await win.waitForTimeout(220)
  const beforeRetry = await retry.boundingBox()
  await retry.click()
  assert.equal(await activity.getByRole('button', { name: '重试中', exact: true }).isDisabled(), true)
  await activity.getByText('合成测试：暂时无法安装，请重试。', { exact: true }).waitFor()
  await win.waitForTimeout(240)
  const afterRetry = await retry.boundingBox()
  assert.ok(Math.abs(beforeRetry.y - afterRetry.y) < 1, 'Retry failure detail must not displace the action')
  assert.equal(await activity.getAttribute('data-activity-path'), identity)
  await capture('08-activity-failure')
  await win.emulateMedia({ reducedMotion: 'reduce' })
  await phase('complete')
  await activity.locator('[data-activity-status] [data-activity-text-current]').filter({ hasText: '安装完成' }).waitFor()
  assert.equal(await activity.getAttribute('data-activity-phase'), 'complete')
  await activity.getByRole('button', { name: '关闭安装提示', exact: true }).click()
  await activity.waitFor({ state: 'hidden' })
  await win.emulateMedia({ reducedMotion: 'no-preference' })
  checks.push({ name: 'Installation status keeps identity and real retry errors, with stable actions', passed: true, beforeRetry, afterRetry, statusFrames })
}
